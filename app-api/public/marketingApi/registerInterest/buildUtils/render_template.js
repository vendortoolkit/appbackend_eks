const fs = require('fs')
const yaml = require('js-yaml')
const mustache = require('mustache')

// Load layer versions from layer-local-versions.json
const layerVersions = JSON.parse(fs.readFileSync('/home/jtran/workspace/vendortoolkit/app-backend/aws-lambda/app-api/layer-local-versions.json', 'utf8'))

// Load environment variables from env.yaml
const env = yaml.load(fs.readFileSync('env.yaml', 'utf8'))

// Convert env object to YAML block with indentation
function envVarsBlock(obj, indent = 10) {
  return Object.entries(obj)
    .map(([key, value]) => ' '.repeat(indent) + `${key}: "${value}"`)
    .join('\n')
}

// Convert layer ARNs to YAML block with indentation
function layerBlock(layersObj, indent = 8) {
  return Object.values(layersObj)
    .map(layerArn => ' '.repeat(indent) + `- ${layerArn}`)
    .join('\n')
}

// Add ENV_VARS_BLOCK to env for mustache
env.ENV_VARS_BLOCK = envVarsBlock(env)
env.LAYER_BLOCK = layerBlock(layerVersions)

// Load template file
const template = fs.readFileSync('template.yaml.j2', 'utf8')

// Render template with env vars
const output = mustache.render(template, env)

// Write output to template.yaml
const notice = [
  '# ------------------------------------------------------------',
  '# DO NOT EDIT THIS FILE DIRECTLY.',
  '# This file is generated from template.yaml.j2 using env.yaml.',
  '# Make changes in template.yaml.j2 or env.yaml.',
  '# ------------------------------------------------------------\n',
].join('\n')

fs.writeFileSync('template.yaml', notice + output)

console.log('template.yaml generated successfully.')